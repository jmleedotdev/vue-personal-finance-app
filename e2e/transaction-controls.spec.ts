import { expect, test } from '@playwright/test'

for (const width of [320, 375, 600, 768, 1440]) {
  test(`browsing menus are accessible and fit at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/transactions')
    const sort = page.getByRole('combobox', { name: 'Sort transactions' })
    const category = page.getByRole('combobox', { name: 'Filter by category' })
    await expect(sort).toHaveAccessibleDescription('Latest')
    await expect(category).toHaveAccessibleDescription('All Transactions')
    await expect(sort.locator('svg')).toBeVisible({ visible: width < 768 })
    await expect(category.locator('svg')).toBeVisible({ visible: width < 768 })
    await sort.focus()
    await expect(sort).toHaveCSS('outline-style', 'solid')
    await sort.press('ArrowDown')
    await sort.press('End')
    await expect(page.getByRole('option', { name: 'Latest', exact: true })).toHaveAttribute(
      'aria-selected',
      'true',
    )
    await sort.press('Escape')
    await expect(page.getByRole('listbox')).toHaveCount(0)
    await expect(sort).toBeFocused()
    await sort.press('Enter')
    await category.click()
    await expect(page.getByRole('listbox')).toHaveCount(1)
    await expect(sort).toHaveAttribute('aria-expanded', 'false')
    await category.press('e')
    await category.press('Enter')
    await expect(category).toBeFocused()
    await expect(category).toHaveAccessibleDescription('Education')
    await expect(category).toHaveAttribute('data-active', 'true')
    await category.click()
    await expect(page.getByRole('option', { name: 'Education', exact: true })).toHaveAttribute(
      'aria-selected',
      'true',
    )
    await page.getByRole('heading', { name: 'Transactions', exact: true }).click()
    await expect(page.getByRole('listbox')).toHaveCount(0)
    await category.click()
    const bounds = await page.getByRole('listbox').boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await category.press('Home')
    await category.press('Enter')
    await page.evaluate(() => window.scrollTo(0, 80))
    await sort.focus()
    const scroll = await page.evaluate(() => scrollY)
    await sort.press('Enter')
    await sort.press('End')
    await sort.press('Enter')
    await expect(sort).toHaveAccessibleDescription('Lowest')
    await expect(sort).toBeFocused()
    expect(await page.evaluate(() => scrollY)).toBe(scroll)
    await category.focus()
    const beforeCategory = await page.evaluate(() => scrollY)
    await category.press('Enter')
    await category.press('g')
    await category.press('Enter')
    await expect(category).toHaveAccessibleDescription('General')
    await expect(category).toBeFocused()
    expect(await page.evaluate(() => scrollY)).toBe(beforeCategory)
  })
}

test('refresh and browser history restore combined applied controls and replace search drafts', async ({
  page,
}) => {
  await page.goto('/transactions?search=a&page=2')
  const input = page.getByRole('searchbox', { name: 'Search transactions' })
  const category = page.getByRole('combobox', { name: 'Filter by category' })
  const sort = page.getByRole('combobox', { name: 'Sort transactions' })
  await input.fill('not applied')
  await category.click()
  await page.getByRole('option', { name: 'General', exact: true }).click()
  await expect(page).toHaveURL('/transactions?search=a&category=General')
  await sort.click()
  await page.getByRole('option', { name: 'Lowest', exact: true }).click()
  await expect(page.locator('tbody th').first()).toHaveText('Urban Services Hub')
  await input.fill('discard on refresh')
  await page.reload()
  await expect(input).toHaveValue('a')
  await expect(category).toHaveAccessibleDescription('General')
  await expect(sort).toHaveAccessibleDescription('Lowest')
  await input.fill('discard on back')
  await page.goBack()
  await expect(sort).toHaveAccessibleDescription('Latest')
  await expect(input).toHaveValue('a')
  await page.goBack()
  await expect(category).toHaveAccessibleDescription('All Transactions')
  await expect(page.getByRole('button', { name: 'Page 2', exact: true })).toHaveAttribute(
    'aria-current',
    'page',
  )
  await page.goForward()
  await page.goForward()
  await expect(sort).toHaveAccessibleDescription('Lowest')
  await expect(category).toHaveAccessibleDescription('General')
  await expect(page.locator('tbody th').first()).toHaveText('Urban Services Hub')
})
